export function getTechnology(slug: string): TechnologyEntry | undefined {
  return Object.values(technologies).find(t => t.slug === slug || t.id === slug);
}

export function getTechnologyById(id: string): TechnologyEntry | undefined {
  return technologies[id];
}

export function getTechnologiesByCategory(category: string): TechnologyEntry[] {
  return Object.values(technologies).filter(t => t.category === category);
}

export function getTechnologiesBySubcategory(category: string, subcategory: string): TechnologyEntry[] {
  return Object.values(technologies).filter(t => t.category === category && t.subcategory === subcategory);
}

export function getAllCategories(): string[] {
  return [...new Set(Object.values(technologies).map(t => t.category))];
}

export function getAllSubcategories(category: string): string[] {
  return [...new Set(Object.values(technologies).filter(t => t.category === category).map(t => t.subcategory))];
}

export function getFeaturedTechnologies(): TechnologyEntry[] {
  return Object.values(technologies).filter(t => t.featured);
}

export function searchTechnologies(query: string): TechnologyEntry[] {
  const q = query.toLowerCase();
  return Object.values(technologies).filter(t =>
    t.name.toLowerCase().includes(q) ||
    t.tags.some(tag => tag.includes(q)) ||
    t.category.toLowerCase().includes(q) ||
    t.subcategory.toLowerCase().includes(q) ||
    t.description.toLowerCase().includes(q)
  );
}
