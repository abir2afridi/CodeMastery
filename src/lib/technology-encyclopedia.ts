function trackIcon(trackId: string): string {
  const track = enrichedTracks.find(t => t.id === trackId);
  return track?.icon ?? `https://img.icons8.com/color/96/${trackId}.png`;
}

function trackDescription(trackId: string): string {
  const rel = trackRelationships[trackId as keyof typeof trackRelationships];
  const track = enrichedTracks.find(t => t.id === trackId);
  if (!rel && !track) return "";
  const category = rel?.category ?? track?.category ?? "";
  const sub = rel?.subcategory ?? track?.subcategory ?? "";
  return `${track?.title ?? trackId} — ${category} / ${sub}. ${track?.tagline ?? ""}`;
}

